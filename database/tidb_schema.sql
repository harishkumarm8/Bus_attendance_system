CREATE TABLE `students` (
  `student_id` varchar(64) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NOT NULL,
  `reg_no` varchar(100) NOT NULL,
  `student_name` varchar(255) NOT NULL,
  `year` varchar(100) DEFAULT NULL,
  `dept` varchar(150) NOT NULL,
  `bus_no` varchar(50) DEFAULT NULL,
  `drop_point` varchar(150) DEFAULT NULL,
  `drop_point_status` enum('Active','Inactive') NOT NULL DEFAULT 'Inactive',
  `bus_status` enum('Active','Inactive','Not available') NOT NULL DEFAULT 'Inactive',
  PRIMARY KEY (`student_id`),
  KEY `idx_reg` (`reg_no`),
  KEY `idx_active` (`bus_status`,`drop_point_status`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE `buses` (
  `bus_no` varchar(50) NOT NULL,
